// Token Radar model (radar-2): one sealed snapshot in, one ranked board out.
//
// A protocol is pre-token when its snapshot record carries no token at all: no
// market cap, no CoinGecko id, no symbol. The board ranks every rankable
// pre-token protocol in the snapshot — the 40 watchlist protocols plus every
// pre-token protocol below the watchlist floor that is not a wrapped, staked
// or bridged product of a token that already trades. Live-token protocols are never ranked:
// they already trade, so the dashboard shows their market cap as a fact and
// keeps them in a separate view.
//
// Implied value is derived only from the snapshot's own figures, in four
// factors the dashboard states and its sandbox can change:
//
//   market multiple  = the median market-cap / TVL ratio across the snapshot's
//                      own live-token protocols, computed at run time from the
//                      snapshot (about 0.25 on this snapshot). It is the
//                      market's own answer to "what is a dollar of TVL worth
//                      as a token", not a number picked by hand.
//   growth           = clamp(change_7d, -50, +150) per cent; a protocol whose
//                      TVL is growing fast is worth more than one shrinking.
//   maturity         = 0.55 + min(age_days, 1460) / 1460 * 0.45. Age is the
//                      days since DefiLlama first listed the protocol: the
//                      longer it has run with no token on record, the more
//                      launch value has accumulated. Unknown age uses 365.
//   breadth          = 1 + 0.04 * min(chains - 1, 4). A protocol live on more
//                      chains reaches more farmers at launch.
//
//   implied = max(1, round(tvl_usd * marketMultiple * growthMult * maturity * breadth))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the dashboard recomputes each row from the same figures so the page and
// board.json always agree.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_step: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1460,
  unknown_age_days: 365,
  breadth_step: 0.04,
  breadth_max_chains: 4,
};

export const MODEL_VERSION = 'radar-2';
export const LIVE_ROWS = 24;

export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

